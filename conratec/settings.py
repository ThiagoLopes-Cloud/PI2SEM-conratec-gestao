from django.core.exceptions import ImproperlyConfigured
from django.core.management.utils import get_random_secret_key

BASE_DIR = Path(__file__).resolve().parent.parent

DEBUG = os.environ.get("DJANGO_DEBUG", "") == "1"

# Em desenvolvimento a chave é sorteada a cada inicialização para que nenhuma
# credencial fique guardada no repositório. Em produção isso derrubaria a sessão
# de quem estivesse usando o sistema a cada reinício, então a chave é exigida.
SECRET_KEY = os.environ.get("DJANGO_SECRET_KEY")
if not SECRET_KEY:
    if not DEBUG:
        raise ImproperlyConfigured(
            "A variável de ambiente DJANGO_SECRET_KEY não está definida. "
            "Defina uma chave secreta no servidor antes de subir a aplicação, "
            "ou use DJANGO_DEBUG=1 para rodar em modo de desenvolvimento."
        )
    SECRET_KEY = get_random_secret_key()

